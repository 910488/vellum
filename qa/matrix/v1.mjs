function tab(surface, id, fields) {
  const docker = fields.automation === "docker-dev-host";
  return c({
    domain: "tabs",
    surface,
    lane: "desktop",
    necessary: true,
    automation: "desktop-ui",
    verificationSources: ["ui", "backend-invoke", "reload"],
    control: TAB_CONTROL[surface],
    evidence: docker
      ? ["deploy-log.txt", "events.json"]
      : [`screenshots/${surface}-${id}.png`, "events.json"],
    ...fields,
    id: `tab.${surface}.${id}`,
  });
}

