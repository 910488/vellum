export const PASS_CLAIM = Object.freeze({
  platforms: ["windows"],
  excludePlatforms: ["macos"],
  officialLive: "NOT_RUN",
  tabSyncRule:
    "Any new ScreenId in src/screens/registry.ts must add matrix cases covering every new button, setting, and important display field in the same change. tests/qa-matrix.test.ts fails if a ScreenId has no cases.",
});

const CASE_KEYS = [
  "id",
  "domain",
  "surface",
  "lane",
  "necessary",
  "preconditions",
  "steps",
  "expected",
  "verificationSources",
  "automation",
  "evidence",
];

function c(spec) {
  for (const key of CASE_KEYS) {
    if (spec[key] === undefined || spec[key] === null || spec[key] === "") {
      throw new Error(`matrix case missing ${key}: ${spec.id ?? "?"}`);
    }
  }
  if (!REQUIRED_DOMAINS.includes(spec.domain)) {
    throw new Error(`unknown domain ${spec.domain} on ${spec.id}`);
  }
  return Object.freeze({
    macosInPassClaim: false,
    officialLive: false,
    ...spec,
  });
}

